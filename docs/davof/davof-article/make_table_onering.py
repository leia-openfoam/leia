"""Table 3 of the proposal from table3_orders.csv (written by qsvd_onering_convergence.py):
one ring, points only, RMSE; columns torus E0 kappa, torus E1 kappa, torus E3 kappa,
torus E3 position, ellipsoid E3 kappa; a row of orders over the three finest levels.
Run: python3 make_table3_proposal.py  (in this directory) -> table3_proposal.tex"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(HERE, "table3_orders.csv"), newline="")))


def pick(surface, model, quantity, rings="1"):
    for r in rows:
        if (r["surface"], r["rings"], r["model"], r["normals"], r["symmetric"], r["quantity"], r["norm"]) == \
           (surface, rings, model, "0", "0", quantity, "RMSE"):
            return r
    raise KeyError((surface, rings, model, quantity))


COLS = [
    ("torus E0 $\\kappa$", pick("torus", "E0", "curvature")),
    ("torus E1 $\\kappa$", pick("torus", "E1", "curvature")),
    ("torus E3 $\\kappa$", pick("torus", "E3", "curvature")),
    ("torus E3 position", pick("torus", "E3", "position")),
    ("ellipsoid E3 $\\kappa$", pick("ellipsoid", "E3", "curvature")),
]
LEVELS = [("err_N20", 0.2), ("err_N40", 0.1), ("err_N80", 0.05), ("err_N160", 0.025), ("err_N320", 0.0125)]


def sci(x):
    m, e = f"{float(x):.2e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


out = []
out.append("% Generated by figures/qsvd/make_table3_proposal.py from table3_orders.csv; do not edit.")
out.append("\\begin{tabular}{l" + "c" * len(COLS) + "}")
out.append("\\toprule")
out.append("$h$ [mm] & " + " & ".join(c[0] for c in COLS) + " \\\\")
out.append("\\midrule")
for key, h in LEVELS:
    out.append(f"{h:g} & " + " & ".join(sci(c[1][key]) for c in COLS) + " \\\\")
out.append("\\midrule")
out.append("order & " + " & ".join(f"${float(c[1]['order_fine3']):.2f}$" for c in COLS) + " \\\\")
out.append("\\bottomrule")
out.append("\\end{tabular}")
open(os.path.join(HERE, "table3_proposal.tex"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out))
