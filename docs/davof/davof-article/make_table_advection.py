#!/usr/bin/env python3
"""The compact transport tables of the preprint from the exported study tables.

Reads, from ``data/tables`` next to this script, the long tables of the leia studies
``sphereTranslation3D_hex`` and ``planeTranslation3D_hex`` (one row per case, written by
``workflow/scripts/make_davof_advection_table.py``) and the plane gate table, and writes

  table_advection_sphere.tex   rows x Courant numbers: L1(alphaf), L1(n), L1(x) at N = 128
                               with the least-squares order over N = 32, 64, 128, and the
                               shape error; "div." where the run aborted
  table_advection_plane.tex    per row and Courant number the number of the eight cases
                               (two arms x four meshes) that pass the 1e-12 gate, and the
                               run maximum of L1(alphaf) at N = 160 on the normal arm
  table_advection_curved.tex   the dual advection with one surface per cell (studies
                               sphereTranslation3D_hexExactSurface, _hexParaboloid and
                               _hexParaboloidRingFit):
                               end errors, orders per period and after one step, min alpha,
                               the surface defect, the anchor's face shift, CPU per step
  table_advection_curved_plane.tex  the plane gate of the ring-tensor paraboloid
                               (planeTranslation3D_hexParaboloid), as table_advection_plane

Never edit the .tex outputs by hand: change the studies or this script and re-run.
"""
import csv
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TAB = os.path.join(HERE, "data", "tables")

ROWS = [
    ("davof-ringArea", "DAVOF, ring normal"),
    ("davof-cellLocal", "DAVOF, own normal"),
    ("davof-exact", "DAVOF, exact normal (control)"),
    ("davof-plicRDFnormal", "DAVOF, plicRDF normal"),
    ("davof-plicRDFnormal-ring", "DAVOF, plicRDF normal, ring fallback"),
    ("davof-ringFit", "DAVOF, ring quadric"),
    ("davof-sagitta-exact", "DAVOF, sagitta clipping, exact normal"),
    ("davof-sagitta-ringArea", "DAVOF, sagitta clipping, ring normal"),
    ("davof-sagitta-cellSliver", "DAVOF, sagitta clipping, own normal with sliver fallback"),
    ("davof-sagitta-cellLocal", "DAVOF, sagitta clipping, own normal"),
    ("plicRDF", "plicRDF"),
    ("isoAlpha", "isoAlpha"),
]
COS = ["0.1", "0.2", "0.5"]
NS = [32, 64, 128]


def _f(x):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return v if math.isfinite(v) else None


def _order(hs, es):
    pts = [(h, e) for h, e in zip(hs, es) if h and e and e > 0]
    if len(pts) < 2:
        return None
    lh = [math.log(p[0]) for p in pts]
    le = [math.log(p[1]) for p in pts]
    mh, me = sum(lh)/len(lh), sum(le)/len(le)
    sxx = sum((a - mh)**2 for a in lh)
    sxy = sum((a - mh)*(b - me) for a, b in zip(lh, le))
    return sxy/sxx if sxx > 0 else None


def _e(v):
    return "--" if v is None else f"{v:.2e}"


def _p(v):
    return "--" if v is None else f"{v:.2f}"


def sphere():
    path = os.path.join(TAB, "davof_advection_sphereTranslation3D_hex.csv")
    rows = list(csv.DictReader(open(path, newline="")))
    by = {}
    for r in rows:
        by[(r["row"], r["Co"], int(r["N"]))] = r
    out = [
        "% Auto-generated by docs/davof/davof-article/make_table_advection.py -- do not edit.",
        "\\begin{tabular}{llrrrrrrr}",
        "\\toprule",
        "normal & Co & $L_1(\\alpha_f)$ & $p$ & $L_1(\\mathbf{n})$ & $p$ & $L_1(\\mathbf{x})$ & $p$ & $E_{\\mathrm{shape}}$ \\\\",
        "\\midrule",
    ]
    for key, label in ROWS:
        first = True
        for co in COS:
            recs = [by.get((key, co, n)) for n in NS]
            if any(r is None for r in recs):
                continue
            div = any(r["status"] != "completed" for r in recs)
            lead = label if first else ""
            first = False
            if div:
                steps = "/".join(r.get("abortStep", "") or "--" for r in recs)
                out.append(f"{lead} & {co} & \\multicolumn{{7}}{{l}}{{aborted at step {steps}}} \\\\")
                continue
            hs = [1.0/n for n in NS]
            cells = []
            for m in ("L1_alphaf_end", "L1_n_end", "L1_x_end"):
                es = [_f(r.get(m)) for r in recs]
                e = es[-1]
                if e is not None and e < 0:
                    cells += ["--", "--"]
                else:
                    cells += [_e(e), _p(_order(hs, es))]
            cells.append(_e(_f(recs[-1].get("Eshape_end"))))
            out.append(f"{lead} & {co} & " + " & ".join(cells) + " \\\\")
        out.append("\\midrule")
    out[-1] = "\\bottomrule"
    out.append("\\end{tabular}")
    with open(os.path.join(HERE, "table_advection_sphere.tex"), "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote table_advection_sphere.tex")


def plane():
    path = os.path.join(TAB, "davof_advection_planeTranslation3D_hex_gate.csv")
    rows = list(csv.DictReader(open(path, newline="")))
    cos = ["0.05", "0.1", "0.2", "0.5"]
    out = [
        "% Auto-generated by docs/davof/davof-article/make_table_advection.py -- do not edit.",
        "\\begin{tabular}{l" + "r"*len(cos) + "r}",
        "\\toprule",
        "normal & " + " & ".join(f"Co $= {c}$" for c in cos) + " & $\\max_t L_1(\\alpha_f)$, $N = 160$, Co $= 0.5$ \\\\",
        "\\midrule",
    ]
    for key, label in ROWS:
        sel = [r for r in rows if r["row"] == key]
        if not sel:
            continue
        cells = []
        for c in cos:
            s = [r for r in sel if r["Co"] == c]
            if not s:
                cells.append("--"); continue
            if all(r["gate"] == "-" for r in s):
                cells.append("--"); continue
            npass = sum(1 for r in s if r["gate"] == "PASS")
            cells.append(f"{npass}/{len(s)}")
        big = [r for r in sel if r["Co"] == "0.5" and r["arm"] == "normal" and int(r["N"]) == 160]
        v = _f(big[0]["L1_alphaf_max"]) if big else None
        if big and big[0]["gate"] == "-":
            last = _e(_f(big[0]["L1_n_max"])) + " (normal)"
        else:
            last = _e(v)
        out.append(f"{label} & " + " & ".join(cells) + f" & {last} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(HERE, "table_advection_plane.tex"), "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote table_advection_plane.tex")


CROWS = [
    ("sphereTranslation3D_hexExactSurface", "davof-exactSurface-exact", "exact sphere", "exact"),
    ("sphereTranslation3D_hexExactSurface", "davof-exactSurface-cellLocal", "exact sphere", "own"),
    ("sphereTranslation3D_hexExactSurface", "davof-exactSurface-ringArea", "exact sphere", "ring"),
    ("sphereTranslation3D_hexParaboloid", "davof-paraboloidRing-exact", "ring-tensor paraboloid", "exact"),
    ("sphereTranslation3D_hexParaboloid", "davof-paraboloidRing-ringArea", "ring-tensor paraboloid", "ring"),
    ("sphereTranslation3D_hexParaboloidRingFit", "davof-paraboloidRing-ringFit", "ring-tensor paraboloid", "ring quadric"),
    ("sphereTranslation3D_hexParaboloid", "davof-paraboloidRing-cellSliver01", "ring-tensor paraboloid", "own, ring below $0.1h^2$"),
    ("sphereTranslation3D_hexParaboloid", "davof-paraboloidRing-cellLocal", "ring-tensor paraboloid", "own"),
]
PROWS = [
    ("davof-paraboloidRing-exact", "ring-tensor paraboloid, exact normal"),
    ("davof-paraboloidRing-ringArea", "ring-tensor paraboloid, ring normal"),
    ("davof-paraboloidRing-cellSliver01", "ring-tensor paraboloid, own normal, ring below $0.1h^2$"),
    ("davof-paraboloidRing-cellLocal", "ring-tensor paraboloid, own normal"),
]


def _first_step(study):
    """The face-fraction error after the first step per (row, Co, N) from the history table."""
    path = os.path.join(TAB, f"davof_advection_history_{study}.csv")
    if not os.path.exists(path):
        return {}
    first = {}
    for r in csv.DictReader(open(path, newline="")):
        key = (r["row"], r["Co"], int(r["N"]))
        try:
            step = int(float(r["step"]))
        except (TypeError, ValueError):
            continue
        v = _f(r.get("L1_alphaf"))
        if v is None:
            continue
        if key not in first or step < first[key][0]:
            first[key] = (step, v)
    return {k: v[1] for k, v in first.items()}


def curved():
    """The dual advection with one surface per cell: the exact-sphere control and the
    ring-tensor paraboloid positioned by alpha_k (studies hexExactSurface, hexParaboloid):
    per surface, normal and Courant number the end errors at the finest mesh present, the
    least-squares orders over the meshes present, the order of the error after one step,
    the minimum of alpha over the run, the run maximum of the surface defect (L1 over the
    interface cells) and of the mean face shift of the volume anchor, and the CPU time per
    step at the finest mesh."""
    studies = sorted({s for s, *_ in CROWS})
    by, first, ns_of = {}, {}, {}
    for study in studies:
        path = os.path.join(TAB, f"davof_advection_{study}.csv")
        if not os.path.exists(path):
            print(f"curved: {path} missing, skipped")
            continue
        for r in csv.DictReader(open(path, newline="")):
            by[(study, r["row"], r["Co"], int(r["N"]))] = r
            ns_of.setdefault(study, set()).add(int(r["N"]))
        first.update({(study,) + k: v for k, v in _first_step(study).items()})
    if not by:
        return
    out = [
        "% Auto-generated by docs/davof/davof-article/make_table_advection.py -- do not edit.",
        "\\begin{tabular}{llrrrrrrrrrrr}",
        "\\toprule",
        "surface, normal & Co & $L_1(\\alpha_f)$ & $p$ & $p_1$ & $L_1(\\mathbf{n})$ & $p$ & $L_1(\\mathbf{x})$ & $p$ & $E_{\\mathrm{shape}}$ & $\\min_t \\alpha$ & defect & s/step \\\\",
        "\\midrule",
    ]
    for study, key, surf, normal in CROWS:
        ns = sorted(ns_of.get(study, []))
        label = f"{surf}, {normal}"
        firstline = True
        for co in COS:
            recs = [(n, by.get((study, key, co, n))) for n in ns]
            recs = [(n, r) for n, r in recs if r is not None]
            if not recs:
                continue
            lead = label if firstline else ""
            firstline = False
            div = [(n, r) for n, r in recs if r["status"] != "completed"]
            if div:
                steps = "/".join(f"{r.get('abortStep', '') or '--'} ($N={n}$)" for n, r in div)
                out.append(f"{lead} & {co} & \\multicolumn{{11}}{{l}}{{aborted at step {steps}}} \\\\")
                continue
            hs = [1.0/n for n, _ in recs]
            last = recs[-1][1]
            cells = []
            for m in ("L1_alphaf_end",):
                es = [_f(r.get(m)) for _, r in recs]
                e = es[-1]
                roundoff = all(v is not None and v < 1e-10 for v in es)
                cells += [_e(e), "--" if roundoff else _p(_order(hs, es))]
                e1 = [first.get((study, key, co, n)) for n, _ in recs]
                cells.append("--" if roundoff or any(v is None for v in e1) else _p(_order(hs, e1)))
            for m in ("L1_n_end", "L1_x_end"):
                es = [_f(r.get(m)) for _, r in recs]
                cells += [_e(es[-1]), _p(_order(hs, es))]
            cells.append(_e(_f(last.get("Eshape_end"))))
            cells.append(_e(_f(last.get("minAlpha_run"))))
            cells.append(_e(_f(last.get("defectL1_max"))))
            cpu, nst = _f(last.get("cpu")), _f(last.get("nSteps"))
            cells.append("--" if not cpu or not nst else f"{cpu/nst:.2f}")
            out.append(f"{lead} & {co} & " + " & ".join(cells) + " \\\\")
        if not firstline:
            out.append("\\midrule")
    out[-1] = "\\bottomrule"
    out.append("\\end{tabular}")
    with open(os.path.join(HERE, "table_advection_curved.tex"), "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote table_advection_curved.tex")


def curved_plane():
    """The plane gate of the ring-tensor paraboloid (study planeTranslation3D_hexParaboloid),
    in the format of table_advection_plane.tex."""
    path = os.path.join(TAB, "davof_advection_planeTranslation3D_hexParaboloid_gate.csv")
    if not os.path.exists(path):
        print(f"curved_plane: {path} missing, skipped")
        return
    rows = list(csv.DictReader(open(path, newline="")))
    cos = sorted({r["Co"] for r in rows}, key=float)
    nmax = max(int(r["N"]) for r in rows)
    out = [
        "% Auto-generated by docs/davof/davof-article/make_table_advection.py -- do not edit.",
        "\\begin{tabular}{l" + "r"*len(cos) + "r}",
        "\\toprule",
        "surface, normal & " + " & ".join(f"Co $= {c}$" for c in cos) + f" & $\\max_t L_1(\\alpha_f)$, $N = {nmax}$, Co $= {cos[-1]}$ \\\\",
        "\\midrule",
    ]
    for key, label in PROWS:
        sel = [r for r in rows if r["row"] == key]
        if not sel:
            continue
        cells = []
        for c in cos:
            s = [r for r in sel if r["Co"] == c]
            if not s or all(r["gate"] == "-" for r in s):
                cells.append("--"); continue
            npass = sum(1 for r in s if r["gate"] == "PASS")
            cells.append(f"{npass}/{len(s)}")
        big = [r for r in sel if r["Co"] == cos[-1] and r["arm"] == "normal" and int(r["N"]) == nmax]
        last = _e(_f(big[0]["L1_alphaf_max"])) if big else "--"
        out.append(f"{label} & " + " & ".join(cells) + f" & {last} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(HERE, "table_advection_curved_plane.tex"), "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote table_advection_curved_plane.tex")


if __name__ == "__main__":
    sphere()
    plane()
    curved()
    curved_plane()
