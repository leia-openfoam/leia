#!/usr/bin/env python3
"""The table of the bias test (table_bias.tex): the ring area normal rotated by a prescribed
tilt theta_b = c h / R, R = 0.15, about e_z x n (biased: the same sense in every cell;
alternating: the sign by the parity of the cell's index sum), against the plain ring normal.

Reads data/tables/nor_bias_orders.csv and nor_bias_cases.csv (leia branch davof-normal-order,
workflow/scripts/nor_tables.py on the studies nor_biasOb, nor_biasRot, nor_transOb, nor_rot,
N = 32, 64, 128 on 8 ranks) and writes per test, OpenFOAM Courant number and tilt the
least-squares orders over N of the L1 angle error (p), the position error d, the shape
error and L1(1 - n.n_Sigma), the L1 angle at N = 32 relative to the plain ring normal's, the
shape error at N = 128 relative to the plain ring normal's, and the wall clock at N = 128.
Never edit the .tex output by hand.
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TAB = os.path.join(HERE, "data", "tables")
TESTS = [("oblique translation", "nor_biasOb", "nor_transOb", [("0.124039", "0.2"), ("0.620194", "1")]),
         ("rotation", "nor_biasRot", "nor_rot", [("0.0462996198086", "0.2"), ("0.231498099043", "1")])]
TILTS = ["c=0.125", "c=0.25", "c=0.5"]


def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def p(x):
    v = f(x)
    return "--" if v is None else "%.2f" % (0.0 if abs(v) < 0.005 else v)


def main():
    orders = {(r["family"], r["row"], r["Co"]): r for r in csv.DictReader(open(os.path.join(TAB, "nor_bias_orders.csv")))}
    cases = {(r["family"], r["row"], r["Co"], r["N"]): r for r in csv.DictReader(open(os.path.join(TAB, "nor_bias_cases.csv")))}
    out = ["% Auto-generated by make_table_bias.py -- do not edit.",
           "\\begin{tabular}{lllrrrrrrrr}", "\\toprule",
           "test & $\\mathrm{Co}$ & tilt & $c$ & $p$ & $p(d)$ & $p(E_{\\mathrm{shape}})$ & "
           "$p(1-\\mathbf{n}\\cdot\\mathbf{n}_\\Sigma)$ & $L_1(\\theta)/L_1(\\theta)_{\\mathrm{ring}}$, $N=32$ & "
           "$E_{\\mathrm{shape}}/E_{\\mathrm{ring}}$, $N=128$ & wall s \\\\", "\\midrule"]
    first = True
    for label, fb, fr, cos in TESTS:
        for co, ofco in cos:
            if not first:
                out.append("\\midrule")
            first = False
            ring_key = ("davof-planeSurf-ringArea")
            o = orders[(fr, ring_key, co)]
            th32 = f(cases[(fr, ring_key, co, "32")]["angle1"])
            e128 = f(cases[(fr, ring_key, co, "128")]["Eshape"])
            lead = label
            out.append(" & ".join([lead, ofco, "none (ring)", "0", p(o["ls_angle1"]), p(o["ls_pos1"]), p(o["ls_Eshape"]),
                                   p(o["ls_omd1"]), "1", "1",
                                   "%.0f" % f(cases[(fr, ring_key, co, "128")]["clock"])]) + " \\\\")
            for c in TILTS:
                for mode in ("biased", "alternating"):
                    key = "ringTilt %s %s" % (c, mode)
                    o = orders[(fb, key, co)]
                    c32 = cases[(fb, key, co, "32")]
                    c128 = cases[(fb, key, co, "128")]
                    out.append(" & ".join(["", "", mode, c.split("=")[1], p(o["ls_angle1"]), p(o["ls_pos1"]), p(o["ls_Eshape"]),
                                           p(o["ls_omd1"]), "%.2f" % (f(c32["angle1"])/th32),
                                           "%.2f" % (f(c128["Eshape"])/e128), "%.0f" % f(c128["clock"])]) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(HERE, "table_bias.tex"), "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote table_bias.tex")


if __name__ == "__main__":
    main()
