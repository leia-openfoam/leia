#!/usr/bin/env python3
"""The table of the four orders of the normal-order study (table_normal_order.tex).

Reads data/tables/nor_orders.csv and nor_cases.csv (written by workflow/scripts/nor_tables.py
of leia branch davof-normal-order from the studies nor_trans, nor_transOb and nor_rot,
N = 32, 64, 128 on 8 ranks) and writes, per test, OpenFOAM Courant number and normal, the
least-squares orders over N of the L1 angle error theta (p), the in-cell position error d,
the per-step flux error relative to V_k (maximum over the steps, translation only), the
shape error E_shape and L1(1 - n.n_Sigma), and the wall clock of the case at N = 128 on
8 ranks. The exact-normal row has no angle column: its model takes the exact normal at the
centroid of the first positioning and the error is scored at the final centroid, so the
column measures the centroid displacement, not an error of the normal.
Never edit the .tex output by hand: run  python3 make_table_normal_order.py
"""
import csv
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TAB = os.path.join(HERE, "data", "tables")
FAM = {"nor_trans": "axial translation", "nor_transOb": "oblique translation", "nor_rot": "rotation"}
OFCO = {("nor_trans", "0.2"): "0.2", ("nor_transOb", "0.124039"): "0.2", ("nor_transOb", "0.620194"): "1",
        ("nor_rot", "0.0462996198086"): "0.2", ("nor_rot", "0.231498099043"): "1"}
ROWS = [("davof-planeSurf-exact", "exact (control)"), ("davof-planeSurf-ringArea", "ring"),
        ("davof-planeSurf-youngs", "Youngs")]


def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def p(x, nd=2):
    v = f(x)
    return "--" if v is None else ("%.*f" % (nd, 0.0 if abs(v) < 0.005 else v))


def ls_order(ns, es):
    pts = [(1.0/n, e) for n, e in zip(ns, es) if e is not None and e > 0]
    if len(pts) < 2:
        return None
    lh = [math.log(a) for a, _ in pts]
    le = [math.log(b) for _, b in pts]
    mh, me = sum(lh)/len(lh), sum(le)/len(le)
    sxx = sum((a - mh)**2 for a in lh)
    return sum((a - mh)*(b - me) for a, b in zip(lh, le))/sxx if sxx > 0 else None


def main():
    orders = {(r["family"], r["row"], r["Co"]): r for r in csv.DictReader(open(os.path.join(TAB, "nor_orders.csv")))}
    cases = {}
    for r in csv.DictReader(open(os.path.join(TAB, "nor_cases.csv"))):
        cases[(r["family"], r["row"], r["Co"], r["N"])] = r
    out = ["% Auto-generated by make_table_normal_order.py -- do not edit.",
           "\\begin{tabular}{llllrrrrrr}", "\\toprule",
           "test & $\\mathrm{Co}$ & normal & $N$ & $p$ & $p(d)$ & $p(\\Delta V_f)$ & $p(E_{\\mathrm{shape}})$ & "
           "$p(1-\\mathbf{n}\\cdot\\mathbf{n}_\\Sigma)$ & wall s \\\\", "\\midrule"]
    first_block = True
    for fam in ("nor_trans", "nor_transOb", "nor_rot"):
        cos = sorted({k[2] for k in orders if k[0] == fam}, key=float)
        for co in cos:
            if (fam, co) not in OFCO:
                continue
            if OFCO[(fam, co)] == "1" and fam == "nor_trans":
                continue
            if not first_block:
                out.append("\\midrule")
            first_block = False
            lead = FAM[fam]
            for key, label in ROWS:
                o = orders.get((fam, key, co))
                if o is None:
                    continue
                ns = o["Ns"].split()
                nrange = "%s--%s" % (ns[0], ns[-1])
                c128 = cases.get((fam, key, co, "128"))
                wall = "--"
                if c128 is not None and c128["status"] == "completed" and f(c128["clock"]) is not None:
                    wall = "%.0f" % f(c128["clock"])
                elif c128 is not None:
                    wall = "aborted"
                exact = (key == "davof-planeSurf-exact")
                vals = {q: o["ls_" + q] for q in ("angle1", "pos1", "flux1Max", "Eshape", "omd1")}
                done = [n for n in ns if cases.get((fam, key, co, n), {}).get("status") == "completed"]
                if len(done) < len(ns):
                    # a run that aborted has no end state to score: the orders over the completed N
                    nrange = "%s--%s" % (done[0], done[-1])
                    for q in vals:
                        vals[q] = ls_order([int(n) for n in done],
                                           [f(cases[(fam, key, co, n)][q]) for n in done])
                cells = [lead if lead else "", OFCO[(fam, co)], label, nrange,
                         "--" if exact else p(vals["angle1"]), p(vals["pos1"]),
                         p(vals["flux1Max"]) if fam != "nor_rot" else "--", p(vals["Eshape"]),
                         "--" if exact else p(vals["omd1"]), wall]
                out.append(" & ".join(cells) + " \\\\")
                lead = ""
    out += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(HERE, "table_normal_order.tex"), "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote table_normal_order.tex")


if __name__ == "__main__":
    main()
