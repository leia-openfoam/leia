# --------------------------------------------------------------------------- 2D shear
def _shear_streamlines(levels=(0.2, 0.45, 0.7, 0.9)):
    import contourpy
    n = 601
    x = np.linspace(0, 1, n)
    Xg, Yg = np.meshgrid(x, x)
    F = np.sin(math.pi * Xg) * np.sin(math.pi * Yg)
    gen = contourpy.contour_generator(Xg, Yg, F)
    out = []
    for c in levels:
        for line in gen.lines(c):
            pts = np.asarray(line)
            # counterclockwise order (the flow is counterclockwise for cos > 0)
            area = 0.5 * np.sum(pts[:-1, 0] * pts[1:, 1] - pts[1:, 0] * pts[:-1, 1])
            if area < 0:
                pts = pts[::-1]
            step = max(1, len(pts) // 140)
            out.append(pts[::step])
    return out


