def fmt(v):
    return f"{v:.4f}".rstrip("0").rstrip(".") if abs(v) > 1e-12 else "0"


def P(x, y):
    return f"({fmt(x)},{fmt(y)})"


def polyline(points, closed=False):
    s = " -- ".join(P(x, y) for x, y in points)
    return s + (" -- cycle" if closed else "")


# --------------------------------------------------------------------------- 3D projection
class Ortho:
    """Orthographic projection from a camera at azimuth `az` and elevation `el` (degrees):
    v = (cos el cos az, cos el sin az, sin el) points to the camera; the screen right
    vector r = e_z x v/|.|, the screen up vector u = v x r (so z is up on screen). The
    default camera (front, slightly left, above) shows the faces x = 0 (narrow), y = 0 and
    z = L; its front vertical edges stay clear of a droplet at the box centre."""

    def __init__(self, az_deg=-110.0, el_deg=16.0, scale=1.0, origin=(0.0, 0.0)):
        az, el = math.radians(az_deg), math.radians(el_deg)
        v = np.array([math.cos(el) * math.cos(az), math.cos(el) * math.sin(az), math.sin(el)])
        r = np.cross([0.0, 0.0, 1.0], v)
        r /= np.linalg.norm(r)
        u = np.cross(v, r)
        self.R = np.vstack([r, u, v])
        self.s = scale
        self.o = np.array(origin, dtype=float)

    def __call__(self, p):
        q = self.R @ np.asarray(p, dtype=float)
        return (self.s * q[0] + self.o[0], self.s * q[1] + self.o[1])

    def depth(self, p):
        return float((self.R @ np.asarray(p, dtype=float))[2])

    def facing(self, normal):
        return float((self.R @ np.asarray(normal, dtype=float))[2]) > 0


def box_edges(prj, L):
    """(solid, hidden) edge lists of the box [0,Lx]x[0,Ly]x[0,Lz]."""
    Lx, Ly, Lz = L
    V = {(i, j, k): (i * Lx, j * Ly, k * Lz) for i in (0, 1) for j in (0, 1) for k in (0, 1)}
    faces = {  # normal -> vertex keys
        (-1, 0, 0): [(0, j, k) for j in (0, 1) for k in (0, 1)],
        (1, 0, 0): [(1, j, k) for j in (0, 1) for k in (0, 1)],
        (0, -1, 0): [(i, 0, k) for i in (0, 1) for k in (0, 1)],
        (0, 1, 0): [(i, 1, k) for i in (0, 1) for k in (0, 1)],
        (0, 0, -1): [(i, j, 0) for i in (0, 1) for j in (0, 1)],
        (0, 0, 1): [(i, j, 1) for i in (0, 1) for j in (0, 1)],
    }
    visible = {n for n in faces if prj.facing(n)}
    solid, hidden = [], []
    keys = list(V)
    for a in keys:
        for b in keys:
            if a >= b or sum(abs(x - y) for x, y in zip(a, b)) != 1:
                continue
            owners = [n for n, fv in faces.items() if a in fv and b in fv]
            (solid if any(n in visible for n in owners) else hidden).append((V[a], V[b]))
    return solid, hidden, visible


def draw_box(prj, L, part="all"):
    """part = 'hidden' (dashed back edges), 'visible' (edges of the camera-facing faces), or
    'all'. Draw 'hidden', then the interior (droplet), then 'visible': every point of a
    camera-facing face of a convex box is in front of every interior point on its ray."""
    solid, hidden, _ = box_edges(prj, L)
    out = []
    if part in ("hidden", "all"):
        for a, b in hidden:
            out.append(rf"\draw[gcls/hidden] {P(*prj(a))} -- {P(*prj(b))};")
    if part in ("visible", "all"):
        for a, b in solid:
            out.append(rf"\draw[gcls/domain] {P(*prj(a))} -- {P(*prj(b))};")
    return out


def ellipsoid_outline(prj, c, axes, n=180):
    """Silhouette of an axis-aligned ellipsoid: convex hull of its projected surface."""
    from scipy.spatial import ConvexHull
    u = np.linspace(0, 2 * math.pi, 2 * n)
    v = np.linspace(0, math.pi, n)
    pts = []
    for vv in v:
        for uu in u[::3]:
            p = (c[0] + axes[0] * math.cos(uu) * math.sin(vv),
                 c[1] + axes[1] * math.sin(uu) * math.sin(vv),
                 c[2] + axes[2] * math.cos(vv))
            pts.append(prj(p))
    pts = np.array(pts)
    hull = ConvexHull(pts)
    return [tuple(pts[i]) for i in hull.vertices]


def equator(prj, c, axes, n=240):
    """The z = c_z section of the ellipsoid, split into front (visible) and back runs."""
    runs, cur, cur_front = [], [], None
    for k in range(n + 1):
        t = 2 * math.pi * k / n
        p = (c[0] + axes[0] * math.cos(t), c[1] + axes[1] * math.sin(t), c[2])
        front = prj.depth(p) - prj.depth(c) >= 0
        if cur_front is None or front == cur_front:
            cur.append(prj(p))
        else:
            cur.append(prj(p))
            runs.append((cur_front, cur))
            cur = [prj(p)]
        cur_front = front
    runs.append((cur_front, cur))
    return runs


def draw_droplet3D(prj, c, axes, final=None):
    out = []
    hull = ellipsoid_outline(prj, c, axes)
    out.append(rf"\fill[gcls/water] {polyline(hull, closed=True)};")
    for front, pts in equator(prj, c, axes):
        style = "gcls/iface, line width=0.5pt" if front else "gcls/ifacehidden"
        out.append(rf"\draw[{style}] {polyline(pts)};")
    out.append(rf"\draw[gcls/iface] {polyline(hull, closed=True)};")
    if final is not None:
        hullf = ellipsoid_outline(prj, final, axes)
        out.append(rf"\draw[gcls/ifacefinal] {polyline(hullf, closed=True)};")
    return out


def axis_triad(prj, at, length_cm=0.75, labels=("x", "y", "z")):
    """A small x, y, z glyph with its base at the screen point `at` [cm]."""
    out = []
    o = np.array(prj((0.0, 0.0, 0.0)))
    for k, lab in enumerate(labels):
        e = np.zeros(3); e[k] = 1.0
        d = np.array(prj(e)) - o
        d = d / np.linalg.norm(d) * length_cm
        a = at; b = (at[0] + d[0], at[1] + d[1])
        out.append(rf"\draw[gcls/axis] {P(*a)} -- {P(*b)} node[gcls/labs, pos=1.0, anchor={_anchor(a, b)}, inner sep=0.6pt] {{${lab}$}};")
    return out


def _anchor(a, b):
    dx, dy = b[0] - a[0], b[1] - a[1]
    ang = math.degrees(math.atan2(dy, dx))
    for lim, name in ((22.5, "west"), (67.5, "south west"), (112.5, "south"), (157.5, "south east")):
        if -lim <= ang <= lim if lim == 22.5 else False:
            return name
    if -22.5 <= ang <= 22.5: return "west"
    if 22.5 < ang <= 67.5: return "south west"
    if 67.5 < ang <= 112.5: return "south"
    if 112.5 < ang <= 157.5: return "south east"
    if ang > 157.5 or ang < -157.5: return "east"
    if -157.5 <= ang < -112.5: return "north east"
    if -112.5 <= ang < -67.5: return "north"
    return "north west"


def wrap(lines):
    return "\n".join(lines)


