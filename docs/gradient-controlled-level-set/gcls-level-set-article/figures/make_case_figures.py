def case_droplet3D(kind):
    Lmm = 6.0
    prj = Ortho(scale=0.53 if kind == "translating" else 0.6)
    c = (3.0, 3.0, 3.0)
    if kind == "oscillating":
        axes = (1.1, 1.0 / math.sqrt(1.1), 1.0 / math.sqrt(1.1))
    else:
        axes = (1.0, 1.0, 1.0)
    L = [r"\begin{tikzpicture}"]
    L += draw_box(prj, (Lmm, Lmm, Lmm), "hidden")
    final = (c[0] + 1.0, c[1], c[2]) if kind == "translating" else None
    L += draw_droplet3D(prj, c, axes, final=final)
    L += draw_box(prj, (Lmm, Lmm, Lmm), "visible")
    L.append(rf"\fill {P(*prj(c))} circle (0.9pt);")
    xs = [prj((i, j, k))[0] for i in (0, 6) for j in (0, 6) for k in (0, 6)]
    ys = [prj((i, j, k))[1] for i in (0, 6) for j in (0, 6) for k in (0, 6)]
    xmid, ybot, ytop = 0.5 * (min(xs) + max(xs)), min(ys), max(ys)
    L += axis_triad(prj, (min(xs) - 0.25, ybot + 0.05))
    if kind == "translating":
        for (yy, zz) in ((1.2, 4.8), (4.8, 1.2), (4.8, 4.8), (3.0, 3.0)):   # (1.2, 1.2) would cross the axis glyph
            a = prj((-1.4, yy, zz)); b = prj((-0.08, yy, zz))
            L.append(rf"\draw[gcls/vel] {P(*a)} -- {P(*b)};")
        a_mid = prj((-1.4, 3.0, 3.0))
        L.append(rf"\node[gcls/labs, anchor=east] at {P(a_mid[0] - 0.05, a_mid[1])} {{inlet}};")
        f_out = prj((6.0, 3.0, 3.0))
        right = max(xs)
        L.append(rf"\node[gcls/labs, anchor=west, align=left] at {P(right + 0.08, f_out[1])} {{outlet\\($x=L$, back)}};")
        bc = (r"inlet $x=0$: $\mathbf u=U_0\mathbf e_x$, $\alpha=0$, $\partial_n p=0$;\\ outlet $x=L$: $p=0$,"
              r" $\partial_n\mathbf u=\partial_n\alpha=0$;\\ slip on $y,z\in\{0,L\}$;\\ $\partial_n\psi=0$ on all faces")
        ic = r"$\mathbf u(\mathbf x,0)=U_0\mathbf e_x$, $U_0=\SI{0.05}{m/s}$,\\ $T=\SI{0.02}{s}$; dashed: $t=T$ ($U_0T=R$)"
    else:
        bc = r"walls: $\mathbf u=\mathbf 0$ (no slip),\\ $\partial_n p=\partial_n\alpha=\partial_n\psi=0$"
        if kind == "oscillating":
            ic = (r"$\mathbf u(\mathbf x,0)=\mathbf 0$; prolate spheroid,\\ $\psi(\mathbf x,0)$ its signed distance;\\"
                  r" $a=1.1R$ along $x$, $b=c=R/\sqrt{1.1}$;\\ $abc=R^3$, $T=\SI{0.025}{s}$")
        else:
            ic = (r"$\mathbf u(\mathbf x,0)=\mathbf 0$, $\psi(\mathbf x,0)=|\mathbf x-\mathbf x_{\mathrm c}|-R$;\\"
                  r" $\mathbf x_{\mathrm c}=(L/2,L/2,L/2)$, $T=\SI{0.025}{s}$")
    L.append(rf"\node[gcls/bc, anchor=north] (bc) at {P(xmid, ybot - 0.12)} {{{bc}}};")
    L.append(rf"\node[gcls/ic, anchor=north] at ($(bc.south) + (0,-0.08)$) {{{ic}}};")
    L.append(rf"\node[gcls/labs, anchor=south] at {P(xmid, ytop + 0.08)} {{$L=\SI{{6}}{{mm}}$, $R=\SI{{1}}{{mm}}$}};")
    L.append(r"\end{tikzpicture}")
    return wrap(L)


